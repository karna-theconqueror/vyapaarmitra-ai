import { Link } from 'react-router-dom'
import { api } from '../api.js'
import { TrendChart } from '../components/Charts.jsx'
import { Empty, Notice, SeverityDot, Spinner, Stat } from '../components/ui.jsx'
import { costMap, dailyTrend } from '../lib/analytics.js'
import { dateLabel, inr, todayISO } from '../lib/format.js'
import { useAsync } from '../lib/useAsync.js'

const MODULE_BADGE = {
  ProfitGuard: 'badge-ok',
  StockSense: 'badge-warn',
  'Customer Comeback': 'badge-info',
  VoiceDukaan: 'badge-mute',
  'Unified Advisor': 'badge-mute',
}

function Signal({ signal }) {
  return (
    <li
      style={{
        display: 'flex',
        gap: 10,
        padding: '0.7rem 0',
        borderTop: '1px solid #f2eee6',
      }}
    >
      <SeverityDot severity={signal.severity} />
      <div style={{ minWidth: 0 }}>
        <div style={{ display: 'flex', gap: 8, alignItems: 'center', flexWrap: 'wrap' }}>
          <span className={`badge ${MODULE_BADGE[signal.module] || 'badge-mute'}`}>
            {signal.module}
          </span>
          <strong style={{ fontSize: '0.92rem' }}>{signal.title}</strong>
        </div>
        <p className="muted" style={{ fontSize: '0.86rem', marginTop: 4 }}>
          {signal.detail}
        </p>
        <p style={{ fontSize: '0.84rem', marginTop: 3 }}>
          <strong>Suggested:</strong> {signal.action}
        </p>
        <p className="hint" style={{ marginTop: 3 }}>
          Basis: {signal.basis}
        </p>
      </div>
    </li>
  )
}

export default function Dashboard() {
  const { data, error, loading, reload } = useAsync(() => api.dashboard())
  const sales = useAsync(() => api.sales())
  const profit = useAsync(() => api.profitProducts())

  if (loading && !data) return <Spinner label="Loading your daily brief…" />
  if (error && !data) return <Notice kind="err">{error}</Notice>
  if (!data) return null

  const { merchant, summary, low_stock, advisor, due_followup_count } = data
  const greeting = new Date().getHours() < 12 ? 'Good morning' : new Date().getHours() < 17 ? 'Good afternoon' : 'Good evening'
  const trend = dailyTrend(sales.data ?? [], costMap(profit.data?.rows ?? []))
  const todaySales = (sales.data ?? []).filter((s) => s.sale_date === todayISO())

  return (
    <div style={{ display: 'grid', gap: 14 }}>
      <div
        style={{
          display: 'flex',
          alignItems: 'flex-end',
          justifyContent: 'space-between',
          gap: 12,
          flexWrap: 'wrap',
        }}
      >
        <div>
          <div className="panel-title">{dateLabel(todayISO())}</div>
          <h1 style={{ fontSize: '1.6rem', marginTop: 4 }}>
            {greeting}
            {merchant.owner_name ? `, ${merchant.owner_name}` : ''}
          </h1>
          <p className="muted" style={{ fontSize: '0.9rem', marginTop: 4 }}>
            {merchant.shop_name} · {merchant.business_type}
          </p>
        </div>
        <button className="btn btn-ghost" onClick={reload} disabled={loading}>
          {loading ? 'Refreshing…' : '↻ Refresh'}
        </button>
      </div>

      {error ? <Notice kind="err">{error}</Notice> : null}

      {/* Snapshot */}
      <div
        style={{
          display: 'grid',
          gap: 10,
          gridTemplateColumns: 'repeat(auto-fit, minmax(190px, 1fr))',
        }}
      >
        <Stat
          label="Today's revenue"
          value={inr(summary.revenue)}
          sub={`${summary.units_sold} units across ${summary.sales_count} sale(s)`}
        />
        <Stat
          label="Est. gross profit"
          value={summary.estimated_gross_profit === null ? '—' : inr(summary.estimated_gross_profit)}
          sub="Estimate from entered cost & price"
          tone="good"
        />
        <Stat
          label="Low stock alerts"
          value={low_stock.count}
          sub={low_stock.count ? 'Items at or below your level' : 'All items above alert level'}
          tone={low_stock.count ? 'warn' : 'plain'}
        />
        <Stat
          label="Follow-ups due"
          value={due_followup_count}
          sub={due_followup_count ? 'Due today or overdue' : 'Nothing due today'}
          tone={due_followup_count ? 'warn' : 'plain'}
        />
      </div>

      <div style={{ display: 'grid', gap: 14 }}>
        {/* Advisor brief */}
        <section className="card">
          <div
            style={{
              display: 'flex',
              justifyContent: 'space-between',
              gap: 10,
              alignItems: 'center',
              flexWrap: 'wrap',
            }}
          >
            <div>
              <div className="panel-title">Unified AI Business Advisor</div>
              <h2 style={{ fontSize: '1.15rem', marginTop: 4 }}>{advisor.headline}</h2>
            </div>
            <span className="badge badge-mute">
              generated by: {advisor.generated_by === 'llm' ? 'AI explanation' : 'transparent rules'}
            </span>
          </div>

          <p style={{ marginTop: 10, fontSize: '0.93rem' }}>{advisor.summary}</p>

          <ul style={{ listStyle: 'none', padding: 0, marginTop: 8 }}>
            {advisor.signals.map((s, i) => (
              <Signal key={i} signal={s} />
            ))}
          </ul>

          <p className="hint" style={{ marginTop: 10, paddingTop: 10, borderTop: '1px solid var(--line)' }}>
            {advisor.disclaimer}
          </p>
        </section>

        <div style={{ display: 'flex', gap: 14, flexWrap: 'wrap', alignItems: 'flex-start' }}>
          {/* Last 7 days — revenue vs estimated profit */}
          <section className="card" style={{ flex: '2 1 440px', minWidth: 0 }}>
            <div className="panel-title">Last 7 days — revenue &amp; estimated profit</div>
            {sales.loading && !sales.data || profit.loading && !profit.data ? (
              <Spinner label="Loading trend…" />
            ) : (
              <div style={{ marginTop: 8 }}>
                <TrendChart data={trend} />
                <p className="hint" style={{ marginTop: 6 }}>
                  Bars = recorded revenue · line = estimated gross profit from your entered
                  costs. Demo data — estimates only.
                </p>
              </div>
            )}
          </section>

        {/* Low stock */}
        <section className="card" style={{ flex: '1 1 260px' }}>
          <div
            style={{
              display: 'flex',
              justifyContent: 'space-between',
              alignItems: 'center',
              gap: 8,
            }}
          >
            <div className="panel-title">Low stock — StockSense</div>
            <Link to="/stock" className="btn btn-ghost" style={{ padding: '0.25rem 0.6rem', fontSize: '0.8rem' }}>
              Open →
            </Link>
          </div>
          {low_stock.top.length === 0 ? (
            <Empty title="No items below your alert level">
              Set a minimum threshold on any product to start receiving alerts.
            </Empty>
          ) : (
            <ul style={{ listStyle: 'none', padding: 0, marginTop: 6 }}>
              {low_stock.top.map((a) => (
                <li
                  key={a.product_id}
                  style={{
                    display: 'flex',
                    gap: 10,
                    alignItems: 'center',
                    padding: '0.55rem 0',
                    borderTop: '1px solid #f2eee6',
                  }}
                >
                  <span
                    className={`badge ${a.level === 'low' ? 'badge-warn' : 'badge-crit'}`}
                    style={{ minWidth: 74, justifyContent: 'center' }}
                  >
                    {a.level.replace('_', ' ')}
                  </span>
                  <div style={{ minWidth: 0 }}>
                    <strong style={{ fontSize: '0.9rem' }}>{a.name}</strong>
                    <div className="hint">
                      {a.quantity} {a.unit}(s) left · alert at {a.min_threshold}
                      {a.suggested_reorder !== null
                        ? ` · suggested reorder ${a.suggested_reorder}`
                        : ''}
                    </div>
                  </div>
                </li>
              ))}
            </ul>
          )}
        </section>

        </div>

        <div style={{ display: 'flex', gap: 14, flexWrap: 'wrap', alignItems: 'flex-start' }}>
        {/* Follow-ups */}
        <section className="card" style={{ flex: '1 1 260px' }}>
          <div
            style={{
              display: 'flex',
              justifyContent: 'space-between',
              alignItems: 'center',
              gap: 8,
            }}
          >
            <div className="panel-title">Follow-ups due — Customer Comeback</div>
            <Link
              to="/customers"
              className="btn btn-ghost"
              style={{ padding: '0.25rem 0.6rem', fontSize: '0.8rem' }}
            >
              Open →
            </Link>
          </div>
          {due_followup_count === 0 ? (
            <Empty title="No follow-ups due">Your due queue is clear for today.</Empty>
          ) : (
            <p style={{ marginTop: 10, fontSize: '0.92rem' }}>
              {due_followup_count} follow-up(s) need a look today. Open Customer Comeback to
              review the message, then send it yourself — no automatic messaging happens here.
            </p>
          )}
        </section>

        {/* Today's sales */}
        <section className="card" style={{ flex: '2 1 440px', minWidth: 0 }}>
          <div
            style={{
              display: 'flex',
              justifyContent: 'space-between',
              alignItems: 'center',
              gap: 8,
            }}
          >
            <div className="panel-title">Today's recorded sales</div>
            <Link to="/profit" className="btn btn-ghost" style={{ padding: '0.25rem 0.6rem', fontSize: '0.8rem' }}>
              Record a sale →
            </Link>
          </div>
          {sales.loading && !sales.data ? (
            <Spinner label="Loading sales…" />
          ) : sales.error ? (
            <Notice kind="err">{sales.error}</Notice>
          ) : todaySales.length === 0 ? (
            <Empty title="No sales recorded today">
              Record a sale in ProfitGuard to see revenue and estimated profit here.
            </Empty>
          ) : (
            <div style={{ overflowX: 'auto', marginTop: 6 }}>
              <table className="table">
                <thead>
                  <tr>
                    <th>Product</th>
                    <th className="num">Qty</th>
                    <th className="num">Unit price</th>
                    <th className="num">Line total</th>
                    <th>Note</th>
                  </tr>
                </thead>
                <tbody>
                  {todaySales.map((s) => (
                    <tr key={s.id}>
                      <td>{s.product_name || `#${s.product_id}`}</td>
                      <td className="num">{s.quantity}</td>
                      <td className="num">{inr(s.unit_price)}</td>
                      <td className="num">{inr(s.unit_price * s.quantity)}</td>
                      <td className="muted">{s.note || '—'}</td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          )}
        </section>
        </div>
      </div>
    </div>
  )
}
